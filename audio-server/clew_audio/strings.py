def japanese() -> bool:
    forced = os.environ.get("CLEW_AUDIO_LANG", "")
    if forced:
        return forced.startswith("ja")
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value:
            return value.startswith("ja")
    return False


TABLE = JA if japanese() else EN


def t(key: str, **params: object) -> str:
    text = TABLE.get(key) or EN[key]
    return text.format(**params) if params else text
